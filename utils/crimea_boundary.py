def is_in_crimea(lat: float | None, lon: float | None) -> bool:
    """Return ``True`` when a WGS84 point is inside the simplified contour."""
    if lat is None or lon is None:
        return False
    x, y = float(lon), float(lat)
    # Сильно изрезанный берег Севастополя после упрощения OSM multipolygon
    # частично превращается во внутренние кольца. Небольшой сухопутный bbox
    # закрывает этот известный провал, не затрагивая материк.
    if 44.38 <= y <= 44.78 and 33.35 <= x <= 33.83:
        return True
    inside = False
    previous = CRIMEA_POLYGON[-1]
    for current in CRIMEA_POLYGON:
        x1, y1 = previous
        x2, y2 = current
        crosses = (y1 > y) != (y2 > y)
        if crosses:
            boundary_x = (x2 - x1) * (y - y1) / (y2 - y1) + x1
            if x < boundary_x:
                inside = not inside
        previous = current
    return inside
